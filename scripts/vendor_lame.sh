#!/usr/bin/env bash
# Fetches LAME 3.100 and vendors the pieces the native build needs into
# core/audio/src/main/cpp/lame/ (gitignored — see docs/audio/LAME_INTEGRATION.md
# for why the sources are never committed). Safe to re-run; it wipes and
# re-populates the target directory each time.
set -euo pipefail

LAME_VERSION="3.100"
LAME_URL="https://sourceforge.net/projects/lame/files/lame/${LAME_VERSION}/lame-${LAME_VERSION}.tar.gz/download"
LAME_SHA256="ddfe36cab873794038ae2c1210557ad34857a4b6bdc515785d1da9e175b1da1e"

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
CPP_DIR="${REPO_ROOT}/core/audio/src/main/cpp"
DEST="${CPP_DIR}/lame"
WORK="$(mktemp -d)"
trap 'rm -rf "${WORK}"' EXIT

echo "vendor-lame: downloading lame-${LAME_VERSION}.tar.gz"
curl -sL --retry 3 -o "${WORK}/lame.tar.gz" "${LAME_URL}"

echo "vendor-lame: verifying checksum"
echo "${LAME_SHA256}  ${WORK}/lame.tar.gz" | sha256sum -c -

echo "vendor-lame: extracting"
tar xzf "${WORK}/lame.tar.gz" -C "${WORK}"
SRC="${WORK}/lame-${LAME_VERSION}"

rm -rf "${DEST}"
mkdir -p "${DEST}/libmp3lame" "${DEST}/include" "${DEST}/mpglib"
cp -r "${SRC}/libmp3lame/." "${DEST}/libmp3lame/"
cp -r "${SRC}/include/." "${DEST}/include/"
cp -r "${SRC}/mpglib/." "${DEST}/mpglib/"

# The upstream tarball ships only config.h.in; the real config.h is normally generated by
# `./configure` on a host build. Hand-written here for bionic/Clang (verified by compiling and
# linking all 20 libmp3lame translation units + the JNI shim for arm64-v8a with this exact file).
cat > "${DEST}/config.h" <<'EOF'
/* Minimal config.h for building libmp3lame 3.100 against the Android NDK (bionic libc, Clang).
 * Hand-written because the vendored source ships only config.h.in (autoconf generates the real
 * one on a host build); values below reflect bionic's actual header/function availability. */
#ifndef LAME_CONFIG_H
#define LAME_CONFIG_H 1

#define STDC_HEADERS 1
#define HAVE_ERRNO_H 1
#define HAVE_FCNTL_H 1
#define HAVE_LIMITS_H 1
#define HAVE_MEMORY_H 1
#define HAVE_STDINT_H 1
#define HAVE_STDLIB_H 1
#define HAVE_STRING_H 1
#define HAVE_STRINGS_H 1
#define HAVE_SYS_STAT_H 1
#define HAVE_SYS_TIME_H 1
#define HAVE_SYS_TYPES_H 1
#define HAVE_UNISTD_H 1
#define HAVE_INTTYPES_H 1
#define HAVE_GETTIMEOFDAY 1
#define HAVE_STRTOL 1
#define HAVE_INT8_T 1
#define HAVE_INT16_T 1
#define HAVE_INT32_T 1
#define HAVE_INT64_T 1
#define HAVE_UINT8_T 1
#define HAVE_UINT16_T 1
#define HAVE_UINT32_T 1
#define HAVE_UINT64_T 1
/* HAVE_MPGLIB deliberately NOT set: it would pull in libmp3lame/mpglib_interface.c's MP3
 * *decode* path (InitMP3/decodeMP3/...), which needs mpglib/*.c that this vendor step doesn't
 * copy. We only ever encode (§12.4) — undefined leaves mpglib_interface.c an empty translation
 * unit (its body is wrapped in one #ifdef HAVE_MPGLIB block). */
#define USE_FAST_LOG 1
#define TAKEHIRO_IEEE754_HACK 1

#define SIZEOF_SHORT 2
#define SIZEOF_INT 4
#define SIZEOF_UNSIGNED_INT 4
#define SIZEOF_FLOAT 4
#define SIZEOF_DOUBLE 8

#define PACKAGE "lame"
#define PACKAGE_NAME "lame"
#define PACKAGE_VERSION "3.100"
#define PACKAGE_STRING "lame 3.100"
#define VERSION "3.100"

/* bionic has no <ieee754.h> (glibc-only); util.h declares fast_log2() unconditionally in terms
 * of this type, which glibc's ieee754.h defines as a plain 32-bit float. */
typedef float ieee754_float32_t;

#endif /* LAME_CONFIG_H */
EOF

echo "vendor-lame: done — $(find "${DEST}/libmp3lame" -name '*.c' | wc -l) libmp3lame sources in ${DEST}"
